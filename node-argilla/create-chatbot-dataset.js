const ArgillaClient = require('./argilla-client');

/**
 * Function to create a dataset for chatbot feedback
 * @returns {Promise<Object|null>} The created or existing dataset, or null if failed
 */
async function createChatbotFeedbackDataset() {
    const client = new ArgillaClient();
    console.log("Connecting to Argilla API at:", process.env.ARGILLA_API_URL);

    // Define the dataset settings for chatbot feedback
    const settings = {
        guidelines: "Rate the chatbot responses on a scale from 1-5 where 1 is poor and 5 is excellent. Then provide feedback on how the response could be improved.",
        fields: [
            {
                name: "user_query",
                title: "User Query",
                description: "The question asked by the user",
                type: "text",
                required: true,
                use_markdown: false
            },
            {
                name: "bot_response",
                title: "Bot Response",
                description: "The response generated by the chatbot",
                type: "text",
                required: true,
                use_markdown: true
            }
        ],
        questions: [
            {
                name: "quality_rating",
                title: "Quality Rating",
                description: "Rate the quality of this response from 1 (poor) to 5 (excellent)",
                type: "rating",
                required: true,
                values: [1, 2, 3, 4, 5]
            },
            {
                name: "improvement_feedback",
                title: "How could this response be improved?",
                description: "Provide specific feedback on how this response could be improved",
                type: "text",
                required: false,
                use_markdown: false
            }
        ]
    };

    // Example chatbot conversations
    const exampleConversations = [
        {
            user_query: "What is machine learning?",
            bot_response: "Machine learning is a subset of artificial intelligence that enables computers to learn from data without explicit programming. It uses statistical techniques to improve performance on tasks over time."
        },
        {
            user_query: "How do I make a chocolate cake?",
            bot_response: "To make a chocolate cake, you need: 2 cups flour, 1 cup sugar, 1/2 cup cocoa powder, 1 tsp baking soda, 1/2 tsp salt, 2 eggs, 1 cup milk, 1/2 cup oil, 2 tsp vanilla extract. Mix dry ingredients, add wet ingredients, bake at 350°F for 30-35 minutes."
        },
        {
            user_query: "Can you explain quantum computing?",
            bot_response: "Quantum computing uses quantum bits or qubits, which can exist in multiple states simultaneously, unlike classical bits. This property allows quantum computers to solve certain problems much faster than traditional computers."
        },
        {
            user_query: "What's the best way to learn a new language?",
            bot_response: "Practice daily, use language learning apps, watch movies in that language, find a conversation partner, and immerse yourself in the culture."
        },
        {
            user_query: "How does climate change work?",
            bot_response: "It's when the weather gets warmer because of pollution."
        },
        {
            user_query: "What are some good exercises for back pain?",
            bot_response: "You should do stretches."
        },
        {
            user_query: "What is the capital of France?",
            bot_response: "The capital of France is Paris, which is known as the 'City of Light'."
        },
        {
            user_query: "How do I fix my wifi connection?",
            bot_response: "Try resetting your router."
        }
    ];

    try {
        // Create or get the dataset
        console.log("Creating or getting dataset 'chatbot_feedback'...");
        const dataset_name = "chatbot_feedback";

        // Force recreate the dataset 
        console.log("Force recreating the dataset with proper fields and questions...");
        const dataset = await client.forceRecreateDataset(dataset_name, settings);

        if (!dataset) {
            console.error("Failed to create dataset");
            return null;
        }

        console.log(`Dataset ID: ${dataset.id}, Name: ${dataset.name}, Status: ${dataset.status}`);

        // Ensure the dataset is published with the correct settings
        console.log("Publishing dataset...");
        const publishSuccess = await client.publishDataset(dataset.id, settings);

        if (!publishSuccess) {
            console.warn("Warning: Failed to publish dataset. Will verify status before adding records.");
        } else {
            console.log("Dataset published successfully.");
        }

        // Verify dataset status
        const updatedDataset = await client.getDatasetById(dataset.id);
        if (!updatedDataset) {
            console.error("Failed to get updated dataset status. Cannot proceed with adding records.");
            return dataset;
        }

        console.log(`Updated dataset status: ${updatedDataset.status}`);

        if (updatedDataset.status !== 'ready') {
            console.error("Dataset is not in 'ready' status. Cannot add records.");
            return updatedDataset;
        }

        // Format records for bulk creation
        console.log("Preparing records for submission...");
        const recordsData = exampleConversations.map(conv => ({
            fields: {
                user_query: conv.user_query,
                bot_response: conv.bot_response
            },
            metadata: {
                source: "node_example_script",
                created_at: new Date().toISOString()
            }
        }));

        // Add records in bulk
        console.log(`Adding ${recordsData.length} records to dataset...`);
        const result = await client.addRecordsToDataset(dataset.id, recordsData);

        if (result) {
            console.log(`Successfully added ${recordsData.length} records to dataset ${dataset.name}`);
            console.log(`Total records added: ${recordsData.length}`);
        } else {
            console.error(`Failed to add records to dataset ${dataset.name}`);
        }

        return updatedDataset;
    } catch (error) {
        console.error("Error in createChatbotFeedbackDataset:", error.message);
        if (error.stack) {
            console.error(error.stack);
        }
        return null;
    }
}

module.exports = createChatbotFeedbackDataset; 