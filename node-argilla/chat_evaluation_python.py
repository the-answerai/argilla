import argilla as rg
import json
import os
from typing import List, Dict, Any, Optional

def format_agent_reasoning(chat: Dict[str, Any]) -> str:
    """Format the agent reasoning from the chat data"""
    if not chat.get("agentReasoning") or not isinstance(chat["agentReasoning"], list) or len(chat["agentReasoning"]) == 0:
        return "No reasoning data available"
    
    reasoning_texts = []
    for agent in chat["agentReasoning"]:
        reasoning = f"Agent: {agent.get('agentName', 'Unnamed')}\n"
        
        # Add messages
        if agent.get("messages") and isinstance(agent["messages"], list) and len(agent["messages"]) > 0:
            reasoning += f"\nMessages:\n{chr(10).join(agent['messages'])}\n"
        
        # Add state if available
        if agent.get("state") and isinstance(agent["state"], dict) and len(agent["state"]) > 0:
            reasoning += f"\nState: {json.dumps(agent['state'], indent=2)}\n"
        
        reasoning_texts.append(reasoning)
    
    return "\n\n".join(reasoning_texts)

def format_used_tools(chat: Dict[str, Any]) -> str:
    """Format the used tools from the chat data"""
    if not chat.get("usedTools") or not isinstance(chat["usedTools"], list) or len(chat["usedTools"]) == 0:
        return "No tools used"
    
    tool_texts = []
    for tool in chat["usedTools"]:
        tool_info = f"Tool: {tool.get('tool', 'Unknown')}\n"
        
        if tool.get("toolInput"):
            tool_info += f"Input: {json.dumps(tool['toolInput'], indent=2)}\n"
        
        if tool.get("toolOutput"):
            if isinstance(tool["toolOutput"], str):
                tool_info += f"Output: {tool['toolOutput']}\n"
            else:
                tool_info += f"Output: {json.dumps(tool['toolOutput'], indent=2)}\n"
        
        tool_texts.append(tool_info)
    
    return "\n\n".join(tool_texts)

def format_source_documents(chat: Dict[str, Any]) -> str:
    """Format the source documents from the chat data"""
    if not chat.get("sourceDocuments") or not isinstance(chat["sourceDocuments"], list) or len(chat["sourceDocuments"]) == 0:
        return "No source documents referenced"
    
    doc_texts = []
    for i, doc in enumerate(chat["sourceDocuments"]):
        doc_info = f"Document {i + 1}:\n"
        
        if doc.get("metadata"):
            doc_info += f"Metadata: {json.dumps(doc['metadata'], indent=2)}\n"
        
        if doc.get("pageContent"):
            doc_info += f"Content: {doc['pageContent']}\n"
        
        doc_texts.append(doc_info)
    
    return "\n\n".join(doc_texts)

def transform_chat_to_argilla_records(chat_messages: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Transform chat messages to Argilla records format"""
    if not isinstance(chat_messages, list) or len(chat_messages) == 0:
        print("Invalid or empty chat messages array")
        return []
    
    records = []
    for chat in chat_messages:
        # Extract user query and AI response based on role
        user_query = chat.get("content", "No user query available") if chat.get("role") == "userMessage" else "No user query available"
        ai_response = chat.get("content", "No AI response available") if chat.get("role") == "apiMessage" else "No AI response available"
        
        # Format other fields
        agent_reasoning = format_agent_reasoning(chat)
        used_tools = format_used_tools(chat)
        source_documents = format_source_documents(chat)
        
        # Create the record
        record = rg.FeedbackRecord(
            fields={
                "user_query": user_query,
                "ai_response": ai_response,
                "agent_reasoning": agent_reasoning,
                "used_tools": used_tools,
                "source_documents": source_documents
            },
            metadata={
                "chat_id": chat.get("chatId", "unknown"),
                "created_date": chat.get("createdDate", "unknown"),
                "session_id": chat.get("sessionId", "unknown")
            }
        )
        records.append(record)
    
    return records

def create_chat_evaluation_dataset() -> Optional[rg.FeedbackDataset]:
    """Create a chat evaluation dataset in Argilla"""
    try:
        # Define the fields and questions for the dataset
        fields = [
            rg.TextField(name="user_query", title="User Query", 
                         description="The question asked by the user", required=True),
            rg.TextField(name="ai_response", title="AI Response", 
                         description="The response generated by the AI", use_markdown=True, required=True),
            rg.TextField(name="agent_reasoning", title="Agent Reasoning", 
                         description="The reasoning process of the agent", use_markdown=True, required=True),
            rg.TextField(name="used_tools", title="Tools Used", 
                         description="The tools used during the conversation", use_markdown=True, required=False),
            rg.TextField(name="source_documents", title="Source Documents", 
                         description="Documents referenced during the conversation", use_markdown=True, required=False)
        ]
        
        questions = [
            rg.RatingQuestion(
                name="information_quality",
                title="Information Quality",
                description="Rate the accuracy and relevance of the information provided",
                required=True,
                values=[1, 2, 3, 4, 5]
            ),
            rg.RatingQuestion(
                name="tool_usage",
                title="Tool Usage Effectiveness",
                description="Rate how effectively tools were used to answer the query",
                required=True,
                values=[1, 2, 3, 4, 5]
            ),
            rg.RatingQuestion(
                name="response_quality",
                title="Overall Response Quality",
                description="Rate the overall quality and helpfulness of the response",
                required=True,
                values=[1, 2, 3, 4, 5]
            ),
            rg.RatingQuestion(
                name="document_relevance",
                title="Document Relevance",
                description="Rate the relevance of the referenced documents",
                required=False,
                values=[1, 2, 3, 4, 5]
            ),
            rg.TextQuestion(
                name="improvement_feedback",
                title="Improvement Suggestions",
                description="Provide specific feedback on how this response could be improved",
                required=False
            )
        ]
        
        guidelines = """
        Evaluate the quality of AI chat conversations by rating different aspects.
        Consider the accuracy and relevance of information, the effective use of tools,
        the quality of the overall response, and the documents referenced.
        """
        
        # Create the dataset
        dataset = rg.FeedbackDataset(
            fields=fields,
            questions=questions,
            guidelines=guidelines
        )
        
        return dataset
    
    except Exception as e:
        print(f"Error creating chat evaluation dataset: {str(e)}")
        return None

def main():
    """Main function to create the dataset and load chat data"""
    # Initialize Argilla client
    rg.init(
        api_url=os.environ.get("ARGILLA_API_URL", "http://localhost:6900"),
        api_key=os.environ.get("ARGILLA_API_KEY", "argilla.apikey"),
    )
    
    print("Creating chat evaluation dataset...")
    dataset = create_chat_evaluation_dataset()
    if not dataset:
        print("Failed to create dataset. Exiting.")
        return
    
    # Push the dataset to Argilla
    dataset_name = "chat_evaluation_python"
    workspace = os.environ.get("ARGILLA_WORKSPACE", "admin")
    
    print(f"Pushing dataset '{dataset_name}' to workspace '{workspace}'")
    remote_dataset = dataset.push_to_argilla(name=dataset_name, workspace=workspace)
    
    # Load the chat data
    chat_data_file = os.path.join("examples", "answerai-chat-example.json")
    print(f"Loading chat data from {chat_data_file}...")
    
    try:
        with open(chat_data_file, "r") as f:
            chat_data = json.load(f)
        
        print(f"Loaded {len(chat_data)} chat messages")
        
        # Transform chat data to Argilla records
        print("Transforming chat data to Argilla records...")
        records = transform_chat_to_argilla_records(chat_data)
        
        print(f"Transformed {len(records)} records")
        
        # Add records to the dataset
        if records:
            print(f"Adding {len(records)} records to dataset...")
            remote_dataset.add_records(records)
            print("Records added successfully!")
        else:
            print("No records to add.")
        
        print("Process completed successfully!")
        
    except Exception as e:
        print(f"Error processing chat data: {str(e)}")

if __name__ == "__main__":
    main() 